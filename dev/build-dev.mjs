// dev/build-dev.mjs — writes dist-dev/: a copy of the extension that talks to
// the local mock servers instead of Anthropic. Load dist-dev/ unpacked.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CLAUDE_MOCK, CONSOLE_MOCK } from "./mock-server.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "dist-dev");
export const SHIPPED = [
  "manifest.json", "config.js", "background.js", "popup.html", "popup.js",
  "content-script.js", "page-inject.js", "lib", "icons", "LICENSE",
];

const claude = `http://${CLAUDE_MOCK.host}:${CLAUDE_MOCK.port}`;
const con = `http://${CONSOLE_MOCK.host}:${CONSOLE_MOCK.port}`;

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out);
for (const f of SHIPPED) fs.cpSync(path.join(root, f), path.join(out, f), { recursive: true });

fs.writeFileSync(
  path.join(out, "config.js"),
  `// GENERATED by dev/build-dev.mjs — do not ship.\n` +
    `export const CLAUDE_ORIGIN = ${JSON.stringify(claude)};\n` +
    `export const CONSOLE_ORIGIN = ${JSON.stringify(con)};\n` +
    `export const DEBUG = true;\n`
);

const manifest = JSON.parse(fs.readFileSync(path.join(out, "manifest.json"), "utf8"));
manifest.name += " (DEV)";
manifest.host_permissions = [`${claude}/*`];
// Optional, exactly like production, so the Connect flow is the real one.
// --grant-console pre-grants it for headless tests, where nobody can click
// Chrome's permission prompt.
if (process.argv.includes("--grant-console")) {
  manifest.host_permissions.push(`${con}/*`);
  delete manifest.optional_host_permissions;
} else {
  manifest.optional_host_permissions = [`${con}/*`];
}
for (const cs of manifest.content_scripts) cs.matches = [`${claude}/*`];
fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

console.log(`dev build → ${out}`);
